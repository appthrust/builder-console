const d = (iso: string) => new Date(`${iso}T00:00:00Z`)

/** The same formula on rows `from..to` (1-based Excel rows) of 0-based `column`; `{r}` is the row number. */
function fill(column: number, from: number, to: number, template: string): FormulaCell[] {
  const cells: FormulaCell[] = []
  for (let row = from; row <= to; row += 1) cells.push({ row: row - 1, column, formula: template.replace(/\{r\}/g, String(row)) })
  return cells
}

